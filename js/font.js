  const cache = new Map();
  function glyphCanvas(ch, color) {
    const key = ch + color;
    let c = cache.get(key);
    if (c) return c;
    const gl = glyphs[ch] || glyphs['?'];
    c = document.createElement('canvas');
    c.width = gl.w; c.height = H;
    const x = c.getContext('2d');
    x.fillStyle = color;
    for (let y = 0; y < H; y++) for (let i = 0; i < gl.w; i++) if (gl.g[y][i]) x.fillRect(i, y, 1, 1);
    cache.set(key, c);
    return c;
  }
  function charW(ch) { const g = glyphs[ch] || glyphs['?']; return g.w; }
  function measure(str) {
    let w = 0;
    for (const ch of str) w += charW(ch) + 1;
    return Math.max(0, w - 1);
  }
  // y = haut de la ligne (zone d'accents incluse). Hauteur de ligne conseillée : 12.
  function draw(ctx, str, x, y, color = '#fff', shadow = '#101028') {
    x = Math.round(x); y = Math.round(y);
    let cx = x;
    for (const ch of str) {
      if (shadow) ctx.drawImage(glyphCanvas(ch, shadow), cx + 1, y + 1);
      ctx.drawImage(glyphCanvas(ch, color), cx, y);
      cx += charW(ch) + 1;
    }
    return cx - x;
  }
  function drawCentered(ctx, str, cx, y, color, shadow) {
    draw(ctx, str, cx - Math.floor(measure(str) / 2), y, color, shadow);
  }
  function drawRight(ctx, str, rx, y, color, shadow) {
    draw(ctx, str, rx - measure(str), y, color, shadow);
  }
  function wrap(str, maxW) {
    const out = [];
    for (const para of str.split('\n')) {
      const words = para.split(' ');
      let line = '';
      for (const w of words) {
        const t = line ? line + ' ' + w : w;
        if (measure(t) > maxW && line) { out.push(line); line = w; }
        else line = t;
      }
      out.push(line);
    }
    return out;
  }
  return { draw, drawCentered, drawRight, measure, wrap, LINE: 12 };
