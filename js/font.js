  // Construit une grille 11 lignes (-2..8) pour chaque glyphe.
  const H = 11, OFF = 2;
  const glyphs = {};
  function blank(w) { const g = []; for (let i = 0; i < H; i++) g.push(new Array(w).fill(0)); return g; }
  function fromRaw(def) {
    const top = def[0], rows = def.slice(1);
    const w = Math.max(...rows.map(r => r.length));
    const g = blank(w);
    rows.forEach((r, i) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') g[top + i + OFF][x] = 1; });
    return { w, g };
  }
